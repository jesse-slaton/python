"""PowerShell wrapper script generator for Tanium Deploy packages."""

from pathlib import Path

from .models import WindowsUpdate


class PowerShellScriptGenerator:
    """Generates PowerShell wrapper scripts for Tanium Deploy."""

    @staticmethod
    def generate_install_script(
        update: WindowsUpdate,
        update_file_name: str,
        quiet: bool = True,
        no_restart: bool = True,
    ) -> str:
        """Generate PowerShell install wrapper script.

        Args:
            update: The WindowsUpdate object
            update_file_name: Name of the update file (e.g., 'windows10.0-kb5034441-x64.msu')
            quiet: Use quiet installation
            no_restart: Prevent automatic restart

        Returns:
            PowerShell script content
        """
        script = f"""<#
.SYNOPSIS
    Install {update.kb or 'Windows Update'} via Tanium Deploy

.DESCRIPTION
    This script installs {update.title}

    KB: {update.kb or 'N/A'}
    Classification: {update.classification}
    Products: {update.products}

.NOTES
    Generated by update-catalog-fetcher
    Update ID: {update.update_id}
#>

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# Set up logging
$LogPath = Join-Path $env:TEMP "Install-{update.kb or 'Update'}.log"
Start-Transcript -Path $LogPath -Append

try {{
    Write-Host "Installing {update.kb or 'update'}..."

    # Get the update file path
    $UpdateFile = Join-Path $PSScriptRoot "{update_file_name}"

    if (-not (Test-Path $UpdateFile)) {{
        throw "Update file not found: $UpdateFile"
    }}

    Write-Host "Update file: $UpdateFile"
    Write-Host "File size: $((Get-Item $UpdateFile).Length / 1MB) MB"

    # Determine file type and install method
    $Extension = [System.IO.Path]::GetExtension($UpdateFile).ToLower()

    switch ($Extension) {{
        '.msu' {{
            # Windows Update Standalone Installer
            Write-Host "Installing MSU package..."
            $Arguments = @(
                $UpdateFile
"""

        if quiet:
            script += """
                '/quiet'
"""

        if no_restart:
            script += """
                '/norestart'
"""

        script += """
            )

            $Process = Start-Process -FilePath 'wusa.exe' -ArgumentList $Arguments -Wait -PassThru -NoNewWindow
            $ExitCode = $Process.ExitCode
        }}

        '.cab' {{
            # Cabinet file - use DISM
            Write-Host "Installing CAB package..."
            $Arguments = @(
                '/Online'
                '/Add-Package'
                "/PackagePath:$UpdateFile"
"""

        if quiet:
            script += """
                '/Quiet'
"""

        if no_restart:
            script += """
                '/NoRestart'
"""

        script += """
            )

            $Process = Start-Process -FilePath 'dism.exe' -ArgumentList $Arguments -Wait -PassThru -NoNewWindow
            $ExitCode = $Process.ExitCode
        }}

        '.exe' {{
            # Executable installer
            Write-Host "Installing EXE package..."
            $Arguments = @(
"""

        if quiet:
            script += """
                '/quiet'
"""

        if no_restart:
            script += """
                '/norestart'
"""

        script += """
            )

            $Process = Start-Process -FilePath $UpdateFile -ArgumentList $Arguments -Wait -PassThru -NoNewWindow
            $ExitCode = $Process.ExitCode
        }}

        default {{
            throw "Unsupported file type: $Extension"
        }}
    }}

    Write-Host "Installation completed with exit code: $ExitCode"

    # Common success codes for Windows updates
    # 0 = Success
    # 3010 = Success, reboot required
    # 2359302 = Already installed
    $SuccessCodes = @(0, 3010, 2359302)

    if ($ExitCode -in $SuccessCodes) {{
        Write-Host "Installation successful!"

        if ($ExitCode -eq 3010) {{
            Write-Warning "A restart is required to complete the installation."
        }}

        Stop-Transcript
        exit 0
    }}
    else {{
        throw "Installation failed with exit code: $ExitCode"
    }}
}}
catch {{
    Write-Error "Installation failed: $_"
    Stop-Transcript
    exit 1
}}
"""
        return script

    @staticmethod
    def generate_remove_script(
        update: WindowsUpdate,
        quiet: bool = True,
        no_restart: bool = True,
    ) -> str:
        """Generate PowerShell remove wrapper script.

        Args:
            update: The WindowsUpdate object
            quiet: Use quiet removal
            no_restart: Prevent automatic restart

        Returns:
            PowerShell script content
        """
        kb_number = update.kb_number if update.kb else "UNKNOWN"

        script = f"""<#
.SYNOPSIS
    Remove {update.kb or 'Windows Update'} via Tanium Deploy

.DESCRIPTION
    This script removes {update.title}

    KB: {update.kb or 'N/A'}
    Classification: {update.classification}
    Products: {update.products}

.NOTES
    Generated by update-catalog-fetcher
    Update ID: {update.update_id}
#>

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# Set up logging
$LogPath = Join-Path $env:TEMP "Remove-{update.kb or 'Update'}.log"
Start-Transcript -Path $LogPath -Append

try {{
    Write-Host "Removing {update.kb or 'update'}..."

    $KBNumber = "{kb_number}"

    # Try to find the installed update
    Write-Host "Searching for installed update KB$KBNumber..."

    # Method 1: Try Get-HotFix (works for some updates)
    $HotFix = Get-HotFix -Id "KB$KBNumber" -ErrorAction SilentlyContinue

    if ($HotFix) {{
        Write-Host "Found update via Get-HotFix"

        # Use wusa to uninstall
        $Arguments = @(
            '/uninstall'
            "/kb:$KBNumber"
"""

        if quiet:
            script += """
            '/quiet'
"""

        if no_restart:
            script += """
            '/norestart'
"""

        script += """
        )

        $Process = Start-Process -FilePath 'wusa.exe' -ArgumentList $Arguments -Wait -PassThru -NoNewWindow
        $ExitCode = $Process.ExitCode
    }}
    else {{
        # Method 2: Try DISM for package removal
        Write-Host "Attempting removal via DISM..."

        # Get installed packages
        $Packages = dism /online /get-packages | Select-String "Package Identity" | ForEach-Object {{
            $_.ToString().Replace("Package Identity : ", "").Trim()
        }}

        # Find package matching KB
        $TargetPackage = $Packages | Where-Object {{ $_ -match "KB$KBNumber" }} | Select-Object -First 1

        if ($TargetPackage) {{
            Write-Host "Found package: $TargetPackage"

            $Arguments = @(
                '/Online'
                '/Remove-Package'
                "/PackageName:$TargetPackage"
"""

        if quiet:
            script += """
                '/Quiet'
"""

        if no_restart:
            script += """
                '/NoRestart'
"""

        script += """
            )

            $Process = Start-Process -FilePath 'dism.exe' -ArgumentList $Arguments -Wait -PassThru -NoNewWindow
            $ExitCode = $Process.ExitCode
        }}
        else {{
            Write-Warning "Update KB$KBNumber not found on system. It may not be installed."
            Stop-Transcript
            exit 0
        }}
    }}

    Write-Host "Removal completed with exit code: $ExitCode"

    # Common success codes
    # 0 = Success
    # 3010 = Success, reboot required
    # 2359303 = Not installed
    $SuccessCodes = @(0, 3010, 2359303)

    if ($ExitCode -in $SuccessCodes) {{
        Write-Host "Removal successful!"

        if ($ExitCode -eq 3010) {{
            Write-Warning "A restart is required to complete the removal."
        }}

        Stop-Transcript
        exit 0
    }}
    else {{
        throw "Removal failed with exit code: $ExitCode"
    }}
}}
catch {{
    Write-Error "Removal failed: $_"
    Stop-Transcript
    exit 1
}}
"""
        return script

    @staticmethod
    def save_script(script_content: str, output_path: Path) -> Path:
        """Save a PowerShell script to disk.

        Args:
            script_content: The PowerShell script content
            output_path: Path to save the script

        Returns:
            Path to the saved script
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)

        with open(output_path, "w", encoding="utf-8-sig") as f:
            f.write(script_content)

        return output_path
